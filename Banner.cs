    const int Height = 6;

    static readonly Color From = new(168, 85, 247);

    static readonly Color To = new(56, 189, 248);

    // Writes the banner and a blank line, or nothing when it does not fit.
    public static void Write(string text)
    {
        if (Create(text) is { } banner)
        {
            AnsiConsole.Write(banner);
            AnsiConsole.WriteLine();
        }
    }

    // Null when the text has a character without a glyph or is wider than the console.
    public static IRenderable? Create(string text)
    {
        text = text.ToUpperInvariant();
        if (!text.All(Glyphs.ContainsKey))
        {
            return null;
        }

        var lines = Enumerable.Range(0, Height).Select(row => string.Concat(text.Select(letter => Glyphs[letter][row]))).ToArray();
        var width = lines[0].Length;
        if (width > AnsiConsole.Profile.Width)
        {
            return null;
        }

        var markup = new StringBuilder();
        foreach (var line in lines)
        {
            for (var column = 0; column < width; column++)
            {
                var character = line[column];
                if (character == ' ')
                {
                    markup.Append(' ');
                    continue;
                }

                // Purple on the left to blue on the right; the outline is a darker shade of the same color.
                var color = From.Blend(To, (float)column / Math.Max(width - 1, 1));
                if (character is not ('█' or '▄' or '▀'))
                {
                    color = color.Blend(Color.Black, 0.55f);
                }

                markup.Append($"[{color.ToMarkup()}]{character}[/]");
            }

            markup.Append('\n');
        }

        return new Markup(markup.ToString());
    }
